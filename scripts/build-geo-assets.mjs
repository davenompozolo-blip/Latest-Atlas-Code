#!/usr/bin/env node
// Geographic surface — vendored country geometry and the country_ref seed.
//
//   node scripts/build-geo-assets.mjs <ne_110m.geojson> <ne_50m.geojson>
//
// Inputs are Natural Earth admin-0 countries (public domain), e.g.
//   https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson
//   https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
//
// Outputs:
//   public/geo/countries-110m.json   TopoJSON, feature id = ISO 3166-1 alpha-2
//   public/geo/countries-50m.json    same, lazy-loaded past zoom 4
//   supabase/seed/country_ref.sql    INSERT for country_ref, from the 50m set
//
// THE JOIN KEY IS ISO_A2_EH, NEVER ISO_A2. Natural Earth publishes ISO_A2 as
// 'CN-TW' for Taiwan and '-99' for France and Norway, so keying on ISO_A2
// would drop TSM's domicile and two of Europe's largest markets off the map
// with nothing on screen to say so. ISO_A2_EH ("ever held") carries TW, FR
// and NO. Features whose EH code is still '-99' (Somaliland, N. Cyprus,
// Siachen) keep their geometry with a null id: they draw, and nothing joins.

import fs from 'node:fs';
import path from 'node:path';
import { topology } from 'topojson-server';

const [, , in110, in50] = process.argv;
if (!in110 || !in50) {
    console.error('usage: build-geo-assets.mjs <ne_110m.geojson> <ne_50m.geojson>');
    process.exit(2);
}

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');

function iso2Of(p) {
    const c = p.ISO_A2_EH;
    return typeof c === 'string' && /^[A-Z]{2}$/.test(c) ? c : null;
}

function slim(fc) {
    return {
        type: 'FeatureCollection',
        features: fc.features.map((f) => ({
            type: 'Feature',
            id: iso2Of(f.properties),
            properties: { name: f.properties.NAME },
            geometry: f.geometry,
        })),
    };
}

function writeTopo(src, out, quantization) {
    const fc = slim(JSON.parse(fs.readFileSync(src, 'utf8')));
    const topo = topology({ countries: fc }, quantization);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, JSON.stringify(topo));
    const kb = (fs.statSync(out).size / 1024).toFixed(0);
    console.log(`${path.relative(ROOT, out)}  ${fc.features.length} features  ${kb} KB`);
    return fc;
}

writeTopo(in110, path.join(ROOT, 'public/geo/countries-110m.json'), 1e5);
writeTopo(in50, path.join(ROOT, 'public/geo/countries-50m.json'), 1e5);

// ── country_ref seed ────────────────────────────────────────────────────────
// One row per ISO code. Where a code appears on several features (AU also
// labels Ashmore and Cartier Is. and the Indian Ocean Territories), the row
// comes from the feature whose ADMIN is its own sovereign — the country, not
// its dependency — falling back to the most populous.
const raw = JSON.parse(fs.readFileSync(in50, 'utf8'));
const byIso = new Map();
for (const f of raw.features) {
    const p = f.properties;
    const iso2 = iso2Of(p);
    if (!iso2) continue;
    const prev = byIso.get(iso2);
    const own = p.ADMIN === p.SOVEREIGNT;
    if (!prev || (own && !prev.own) || (own === prev.own && (p.POP_EST || 0) > (prev.p.POP_EST || 0))) {
        byIso.set(iso2, { p, own });
    }
}

const q = (s) => (s == null ? 'null' : "'" + String(s).replace(/'/g, "''") + "'");
const num = (x) => (Number.isFinite(x) ? String(Math.round(x * 1e6) / 1e6) : 'null');

const rows = [...byIso.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([iso2, { p }]) => {
    const iso3 = /^[A-Z]{3}$/.test(p.ISO_A3_EH || '') ? p.ISO_A3_EH : null;
    // ECONOMY is Natural Earth's own 7-way class. 1 and 2 are the developed
    // regions (G7 and non-G7); everything else is emerging, developing or
    // least developed. Crude — the spec says so — and sourced, which a hand
    // list would not be.
    const developed = /^[12]\./.test(p.ECONOMY || '');
    return `  (${q(iso2)}, ${q(iso3)}, ${q(p.NAME_LONG || p.NAME)}, ${q(p.REGION_UN)}, ${q(p.SUBREGION)}, `
        + `${developed}, ${num(p.LABEL_X)}, ${num(p.LABEL_Y)}, ${q(p.ECONOMY)})`;
});

const sql = `-- Generated by scripts/build-geo-assets.mjs from Natural Earth 1:50m admin-0
-- countries (public domain). Do not edit by hand; re-run the script.
-- ${rows.length} countries plus the XX unallocated row.
insert into public.country_ref
  (iso2, iso3, name, region, subregion, is_developed, centroid_lon, centroid_lat, ne_economy)
values
${rows.join(',\n')},
  ('XX', null, 'Unallocated', null, null, null, null, null, null)
on conflict (iso2) do update set
  iso3 = excluded.iso3, name = excluded.name, region = excluded.region,
  subregion = excluded.subregion, is_developed = excluded.is_developed,
  centroid_lon = excluded.centroid_lon, centroid_lat = excluded.centroid_lat,
  ne_economy = excluded.ne_economy;
`;
const seedPath = path.join(ROOT, 'supabase/seed/country_ref.sql');
fs.mkdirSync(path.dirname(seedPath), { recursive: true });
fs.writeFileSync(seedPath, sql);
console.log(`${path.relative(ROOT, seedPath)}  ${rows.length + 1} rows`);
