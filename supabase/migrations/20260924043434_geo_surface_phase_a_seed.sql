insert into public.security_domicile (security_id, iso2, instrument_kind, source, source_note)
select distinct on (a.id) a.id, esu.country, 'issuer', 'finnhub_profile', null
  from public.equity_screener_universe esu
  join public.assets a on a.symbol = esu.symbol
  join public.country_ref cr on cr.iso2 = esu.country and cr.iso2 <> 'XX'
 where a.asset_class not ilike '%option%'
 order by a.id
on conflict (security_id) do nothing;

