-- ------------------------------------------------------------------------
-- 9. The per-account writers: the previous bodies, scoped to the active account
-- ------------------------------------------------------------------------
-- Edits (gen5c.py, each asserted by count): portfolio_id on every read and
-- write of position_verdicts / segment_verdicts / book_risk_daily / sync_log;
-- REFRESH replaced by atlas_rematerialise; a preflight refusal RETURNs instead
-- of RAISEing, so its log row survives.

CREATE OR REPLACE FUNCTION public.atlas_write_verdicts_active(p_as_of date DEFAULT NULL::date, p_logic_version text DEFAULT 'v1:rho0.75:n5:mwr'::text, p_refresh boolean DEFAULT true)
 RETURNS TABLE(out_as_of date, out_logic_version text, out_rows_written integer, out_notes text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
    v_as_of        date;
    v_pos_as_of    date;
    v_last_traded  date;
    v_written      int;
    v_share_sum    numeric;
    v_bad          int;
    v_note         text := '';
    v_log_id       bigint;
    v_pre          jsonb;
    v_failed       text;
    v_existing     int;
    -- MP-5: every row this function reads or writes belongs to the ACTIVE
    -- account. The public atlas_write_verdicts() sets the header per account.
    v_pid          uuid := public.atlas_active_portfolio();
BEGIN
    IF p_refresh THEN
        PERFORM public.atlas_rematerialise(ARRAY['mv_book_daily_weights','mv_book_ex_index',
                                                 'mv_position_returns','mv_position_tier2',
                                                 'mv_position_tier1']);
    END IF;

    v_as_of       := COALESCE(p_as_of, CURRENT_DATE);
    v_pos_as_of   := (SELECT max(pz.as_of_date) FROM public.vw_active_positions pz);
    v_last_traded := public.atlas_last_traded_day();

    INSERT INTO public.sync_log (source, function_name, status, portfolio_id, started_at, details)
    VALUES ('atlas_write_verdicts', 'atlas_write_verdicts', 'running', v_pid, now(),
            jsonb_build_object('as_of', v_as_of, 'logic_version', p_logic_version))
    RETURNING id INTO v_log_id;

    -- ------------------------------------------------------------------
    -- Rev. B §6, last invariant: no verdict row while any position carries
    -- a stale broker row. `position_verdicts` is a history and a row written
    -- against yesterday's book freezes the wrong holdings into the record
    -- permanently - which is exactly the §1 blocker that gated this whole
    -- step. A view recomputes; a history does not.
    -- ------------------------------------------------------------------
    SELECT jsonb_agg(jsonb_build_object('check', check_name, 'passed', passed, 'detail', detail)),
           string_agg(check_name || ': ' || detail, '; ') FILTER (WHERE NOT passed)
      INTO v_pre, v_failed
      FROM public.atlas_verdict_preflight();

    IF v_failed IS NOT NULL THEN
        UPDATE public.sync_log
           SET status = 'skipped', finished_at = now(),
               details = details || jsonb_build_object('reason', 'preflight failed',
                                                      'preflight', v_pre)
         WHERE id = v_log_id;
        -- Refuse by RETURNING, not RAISE: a RAISE rolls back the log row that
        -- records the refusal, and the wrapper runs every account in its own
        -- subtransaction.
        RETURN QUERY SELECT v_as_of, p_logic_version, 0, 'preflight failed: ' || v_failed;
        RETURN;
    END IF;

    -- ------------------------------------------------------------------
    -- The rows
    -- ------------------------------------------------------------------
    WITH open_book AS (
        SELECT r.* FROM public.mv_position_returns r WHERE r.position_state = 'open'
    ),
    risk AS (
        -- Renormalised over the positions we actually rank. vw_risk_analysis
        -- carries 79 rows for 57 open names and its weights sum to 1.0157;
        -- the difference is written out as `residual` rather than absorbed.
        SELECT v.symbol, v.annual_vol, v.dollar_var_95_daily,
               v.weight / NULLIF(sum(v.weight) OVER (), 0) AS w_norm
          FROM public.vw_risk_analysis v
         WHERE v.symbol IN (SELECT symbol FROM open_book)
    ),
    -- defect 3. vw_risk_analysis.marginal_vol_contribution is weight * vol --
    -- no covariance, so positive by construction and with no Euler
    -- additivity. mctr_annual is the real partial derivative and
    -- risk_contribution_annual is already mctr x weight. One scan; the view
    -- is ~340-450 ms.
    mctr AS (
        SELECT m.symbol, m.mctr_annual, m.risk_contribution_annual, m.matrix_as_of
          FROM public.vw_book_mctr m
         WHERE m.symbol IN (SELECT symbol FROM open_book)
    ),
    mx AS (SELECT max(matrix_as_of) AS d FROM mctr),
    clus AS (
        SELECT u.symbol, u.cluster_id
          FROM public.universe_clusters u
         WHERE u.as_of_date = (SELECT max(u2.as_of_date) FROM public.universe_clusters u2)
    ),
    -- Risk share is computed over a PARTITION (universe_clusters), not over
    -- Tier 1's rho >= 0.75 neighbourhood. They are different objects: a
    -- neighbourhood overlaps and covers 17 names, a partition covers the book
    -- and sums to 1. Conflating them is what would break the identity.
    share AS (
        SELECT c.cluster_id,
               sum(mc.risk_contribution_annual) AS contrib
          FROM mctr mc JOIN clus c ON c.symbol = mc.symbol
         GROUP BY c.cluster_id
    ),
    share_n AS (
        SELECT cluster_id, contrib / NULLIF(sum(contrib) OVER (), 0) AS cluster_risk_share
          FROM share
    ),
    -- The cluster leader must not be a leveraged product. SOXL tops five of
    -- the seventeen eligible clusters because a 3x fund takes a levered share
    -- of any move that went the right way; "switch to SOXL" is not advice this
    -- module should be able to emit. Gated on measured volatility rather than
    -- a name match: a leader more than 1.5x the position's own vol is not a
    -- like-for-like substitute whatever it is called.
    leader_vol AS (
        SELECT t.symbol,
               t.cf_best_symbol,
               (SELECT stddev_samp(x.r) * sqrt(252::numeric)
                  FROM (SELECT ph.close / lag(ph.close) OVER (ORDER BY ph.price_date) - 1 AS r
                          FROM public.price_history ph
                          JOIN public.vw_canonical_assets ca ON ca.asset_id = ph.asset_id
                         WHERE ca.symbol = t.cf_best_symbol AND ph."interval" = '1d'
                           AND ph.price_date > v_as_of - 180
                       ) x
                 WHERE x.r IS NOT NULL) AS lead_vol
          FROM public.mv_position_tier1 t
         WHERE t.cluster_eligible AND t.cf_best_symbol IS NOT NULL
    ),
    assembled AS (
        SELECT o.asset_id,
               o.symbol,
               o.position_state,
               COALESCE(p.side, 'long')                                AS side,
               o.engine_status,
               o.engine_reason,
               o.days_held,
               o.first_flow_date,
               o.capital_deployed_usd,
               o.position_mwr_pct,
               o.position_twr_pct,
               o.mark_days_old,
               o.mark_price_date,
               CASE o.engine_status
                   WHEN 'measured'        THEN 'measured'
                   WHEN 'stale_mark'      THEN 'stale_mark'
                   WHEN 'ledger_mismatch' THEN 'ledger_mismatch'
                   WHEN 'basis_mismatch'  THEN 'basis_mismatch'
                   ELSE 'one_sided'
               END                                                     AS verdict_status,
               t1.cluster_eligible,
               t1.cluster_size,
               t1.avg_intra_rho,
               cl.cluster_id,   -- partition, not the tier-1 join (spec 2.4c)
               t1.cf_median_return_pct,
               t1.cf_best_return_pct,
               t1.cf_best_symbol,
               t1.cf_basket_return_pct,
               t1.cluster_dispersion,
               t1.rank_in_cluster,
               bt.thesis_state,
               bt.thesis_state_as_of,
               t1.cluster_members,
               t1.selection_effect_pct,
               t1.regret_vs_best_pct,
               t1.selection_effect_vol_adj,
               t2.cf_book_return_pct,
               t2.excess_vs_book_pct,
               t2.best_correlate_rho,
               t2.best_correlate_symbol,
               fz.frozen_weight_return_pct,
               fz.trading_effect_pct,
               rk.annual_vol,
               mc.mctr_annual AS marginal_vol_contribution,
               rk.dollar_var_95_daily,
               sn.cluster_risk_share,
               lv.lead_vol,
               CASE WHEN COALESCE(t1.cluster_eligible, false) THEN 'cluster'
                    WHEN t2.excess_vs_book_pct IS NOT NULL     THEN 'book'
                    ELSE 'none' END                                    AS peer_basis,
               COALESCE(t1.selection_effect_pct, t2.excess_vs_book_pct) AS active_score
          FROM open_book o
          LEFT JOIN (SELECT t.*, c.cluster_id
                       FROM public.mv_position_tier1 t
                       LEFT JOIN clus c ON c.symbol = t.symbol) t1 ON t1.asset_id = o.asset_id
          LEFT JOIN public.mv_position_tier2 t2 ON t2.asset_id = o.asset_id
          LEFT JOIN public.vw_bench_thesis_state bt ON bt.symbol = o.symbol
          LEFT JOIN public.vw_position_frozen fz ON fz.asset_id = o.asset_id
          LEFT JOIN risk    rk ON rk.symbol = o.symbol
          LEFT JOIN mctr    mc ON mc.symbol = o.symbol
          LEFT JOIN clus    cl ON cl.symbol = o.symbol
          LEFT JOIN share_n sn ON sn.cluster_id = cl.cluster_id
          LEFT JOIN leader_vol lv ON lv.symbol = o.symbol
          LEFT JOIN LATERAL (
                SELECT pp.side FROM public.vw_active_positions pp
                 WHERE pp.asset_id = o.asset_id AND pp.as_of_date = v_pos_as_of
                 LIMIT 1) p ON true
    ),
    labelled AS (
        SELECT a.*,
               CASE WHEN a.verdict_status <> 'measured' OR a.active_score IS NULL THEN NULL
                    WHEN a.active_score >=  0.05 THEN 'leader'
                    WHEN a.active_score >  -0.05 THEN 'holding_own'
                    WHEN a.active_score >= -0.20 THEN 'lagging'
                    ELSE 'cut_candidate'
               END AS verdict_label
          FROM assembled a
    )
    INSERT INTO public.position_verdicts (
        portfolio_id, as_of, logic_version, asset_id, symbol, position_state, side,
        verdict_status, status_reason, price_days_old, last_measurable_date,
        first_entry_date, days_held, capital_deployed_usd,
        position_mwr_pct, position_twr_pct, annualised_return,
        peer_basis, cluster_threshold_rho, cluster_id, cluster_size, avg_intra_rho,
        cf_median_return_pct, cf_best_return_pct, cf_best_symbol, cf_basket_return_pct,
        selection_effect_pct, regret_vs_best_pct, selection_effect_vol_adj,
        position_vol_annual, marginal_vol_contribution, dollar_var_95_daily,
        cluster_risk_share, verdict_label, suggested_reason_code,
        ranking_basis, engine_status, status_detail,
        cluster_eligible, cf_book_return_pct, excess_vs_book_pct,
        best_correlate_rho, best_correlate_symbol,
        frozen_weight_return_pct, trading_effect_pct, cluster_dispersion,
        rank_in_cluster, cluster_members,
        thesis_state, thesis_state_as_of,
        evidence_own_return_known, evidence_staleness_days,
        risk_basis, risk_matrix_as_of)
    SELECT v_pid, v_as_of, p_logic_version, l.asset_id, l.symbol, l.position_state, l.side,
           l.verdict_status, l.engine_reason, l.mark_days_old, l.mark_price_date,
           l.first_flow_date, l.days_held, l.capital_deployed_usd,
           l.position_mwr_pct, l.position_twr_pct,
           -- §2.7 floor. Also a CHECK; asserted here so the job fails loudly
           -- rather than the constraint firing on a row nobody looked at.
           CASE WHEN l.days_held >= 90 THEN l.position_mwr_pct END,
           l.peer_basis, 0.75, l.cluster_id, l.cluster_size, l.avg_intra_rho,
           l.cf_median_return_pct, l.cf_best_return_pct, l.cf_best_symbol, l.cf_basket_return_pct,
           l.selection_effect_pct, l.regret_vs_best_pct, l.selection_effect_vol_adj,
           l.annual_vol, l.marginal_vol_contribution, l.dollar_var_95_daily,
           l.cluster_risk_share, l.verdict_label,
           CASE
               WHEN l.verdict_label = 'cut_candidate' AND l.peer_basis = 'cluster'
                    AND l.cf_best_symbol IS NOT NULL
                    AND l.lead_vol IS NOT NULL AND l.annual_vol IS NOT NULL
                    AND l.lead_vol <= 1.5 * l.annual_vol
                    THEN 'switch_to_cluster_leader'
               WHEN l.verdict_label = 'cut_candidate' AND l.peer_basis = 'cluster'
                    THEN 'cut_underperforming_comparables'
               WHEN l.verdict_label = 'cut_candidate' AND l.peer_basis = 'book'
                    THEN 'trim_concentration'
           END,
           'mwr', l.engine_status, l.engine_reason,
           COALESCE(l.cluster_eligible, false), l.cf_book_return_pct, l.excess_vs_book_pct,
           l.best_correlate_rho, l.best_correlate_symbol,
           l.frozen_weight_return_pct, l.trading_effect_pct, l.cluster_dispersion,
           l.rank_in_cluster, l.cluster_members,
           l.thesis_state, l.thesis_state_as_of,
           (l.verdict_status = 'measured'), l.mark_days_old,
           -- The basis is NULL exactly when both figures are, which the CHECK
           -- enforces as a CASE rather than an OR chain: an OR chain of `=`
           -- comparisons yields NULL on a NULL basis, and a CHECK PASSES on
           -- NULL.
           CASE WHEN l.marginal_vol_contribution IS NULL
                 AND l.cluster_risk_share IS NULL THEN NULL ELSE 'mctr_euler' END,
           CASE WHEN l.marginal_vol_contribution IS NULL
                 AND l.cluster_risk_share IS NULL THEN NULL ELSE mx.d END
      FROM labelled l
      CROSS JOIN mx
    ON CONFLICT (portfolio_id, as_of, asset_id, logic_version) DO NOTHING;

    GET DIAGNOSTICS v_written = ROW_COUNT;

    -- ------------------------------------------------------------------
    -- Rev. B §6, the cross-row invariants. The single-row ones are CHECKs
    -- on the table and cannot be forgotten; these two cannot be CHECKs.
    -- ------------------------------------------------------------------
    SELECT sum(s.share) INTO v_share_sum
      FROM (SELECT DISTINCT coalesce(pv.cluster_id::text, 'pos:' || pv.asset_id::text) AS bucket,
                   pv.cluster_risk_share AS share
              FROM public.position_verdicts pv
             WHERE pv.portfolio_id = v_pid AND pv.as_of = v_as_of AND pv.logic_version = p_logic_version
               AND pv.cluster_risk_share IS NOT NULL) s;

    IF v_share_sum IS NOT NULL AND abs(v_share_sum - 1.0) > 0.005 THEN
        RAISE EXCEPTION 'cluster_risk_share sums to % across the book, not 1.0', v_share_sum;
    END IF;

    SELECT count(*) INTO v_bad
      FROM public.position_verdicts
     WHERE portfolio_id = v_pid AND as_of = v_as_of AND logic_version = p_logic_version
       AND peer_basis = 'none' AND verdict_status = 'measured';
    IF v_bad > 0 THEN
        v_note := v_note || v_bad::text || ' measured positions have no basis; ';
    END IF;

    -- ------------------------------------------------------------------
    -- Book companion
    -- ------------------------------------------------------------------
    INSERT INTO public.book_risk_daily (
        portfolio_id, as_of, logic_version, total_vol_annual, book_var_95_daily,
        sum_contributions, residual, effective_bets, cluster_shares,
        unmapped_theme_weight, cluster_threshold_rho,
        traded_book_return_pct, frozen_book_return_pct, trading_effect_pct,
        positions_cluster_eligible, positions_no_correlate,
        positions_in_matrix, positions_absent_from_matrix,
        vol_basis, vol_matrix_as_of)
    SELECT v_pid, v_as_of, p_logic_version,
           -- Was sum(mvc * weight) * sqrt(252). mvc is already weight * ANNUAL
           -- vol, so that squared the weight AND re-annualised an annual figure
           -- -- two dimensional errors that partly cancelled into a
           -- plausible-looking 10.78% against a true ~19.5%. Read the real
           -- Euler-additive book vol instead (Sigma = D R D, B4).
           mc.vol,
           (SELECT sum(v.dollar_var_95_daily) FROM public.vw_risk_analysis v
             WHERE v.symbol IN (SELECT pv.symbol FROM public.position_verdicts pv
                                 WHERE pv.portfolio_id = v_pid AND pv.as_of = v_as_of AND pv.logic_version = p_logic_version)),
           -- Sum of the Euler risk contributions over the ranked book. Under
           -- MCTR this SUMS TO THE BOOK VOL by construction, so the pair
           -- (sum_contributions, residual) is an identity rather than the
           -- dimensionless product of a per-position figure and a per-cluster
           -- share that stood here before.
           (SELECT sum(m.risk_contribution_annual) FROM public.vw_book_mctr m
             WHERE m.symbol IN (SELECT pv.symbol FROM public.position_verdicts pv
                                 WHERE pv.portfolio_id = v_pid AND pv.as_of = v_as_of AND pv.logic_version = p_logic_version)),
           -- Written out, never swept up (memo v2 §2.8): the gap between the
           -- whole risk view and the positions actually ranked.
           -- The book vol the ranked positions do NOT account for: names the
           -- correlation matrix cannot price. Written out, never swept up.
           mc.vol - (SELECT COALESCE(sum(m.risk_contribution_annual), 0)
                       FROM public.vw_book_mctr m
                      WHERE m.symbol IN (SELECT pv.symbol FROM public.position_verdicts pv
                                          WHERE pv.portfolio_id = v_pid AND pv.as_of = v_as_of
                                            AND pv.logic_version = p_logic_version)),
           (SELECT 1.0 / NULLIF(sum(s.share * s.share), 0)
              FROM (SELECT DISTINCT cluster_id, cluster_risk_share AS share
                      FROM public.position_verdicts
                     WHERE portfolio_id = v_pid AND as_of = v_as_of AND logic_version = p_logic_version
                       AND cluster_risk_share IS NOT NULL) s),
           (SELECT jsonb_object_agg(s.cluster_id::text, round(s.share, 6))
              FROM (SELECT DISTINCT cluster_id, cluster_risk_share AS share
                      FROM public.position_verdicts
                     WHERE portfolio_id = v_pid AND as_of = v_as_of AND logic_version = p_logic_version
                       AND cluster_risk_share IS NOT NULL AND cluster_id IS NOT NULL) s),
           (SELECT COALESCE(sum(v.weight) FILTER (
                     WHERE NOT EXISTS (SELECT 1 FROM public.position_themes pt
                                        WHERE pt.symbol = v.symbol AND pt.theme IS NOT NULL)), 0)
                   / NULLIF(sum(v.weight), 0)
              FROM public.vw_risk_analysis v
             WHERE v.symbol IN (SELECT pv.symbol FROM public.position_verdicts pv
                                 WHERE pv.portfolio_id = v_pid AND pv.as_of = v_as_of AND pv.logic_version = p_logic_version)),
           0.75,
           b.traded_book_return_pct, b.frozen_book_return_pct, b.trading_effect_pct,
           b.positions_cluster_eligible, b.positions_no_correlate,
           (SELECT count(*) FROM public.position_verdicts pv
             WHERE pv.portfolio_id = v_pid AND pv.as_of = v_as_of AND pv.logic_version = p_logic_version
               AND pv.best_correlate_rho IS NOT NULL),
           (SELECT count(*) FROM public.vw_held_symbols_absent_from_matrix),
           -- The basis is NULL exactly when the figure is, so a row can never
           -- claim a method for a number it does not have.
           CASE WHEN mc.vol IS NULL THEN NULL ELSE 'mctr_covariance' END,
           mc.mx
      FROM public.vw_book_frozen_baseline b
      -- One scan, not three: vw_book_mctr is ~340-450 ms and this file's own
      -- history records a view re-derived per reference costing 2,768 ms.
      LEFT JOIN LATERAL (
          SELECT max(m.book_vol_annual)::numeric AS vol,
                 max(m.matrix_as_of)            AS mx
            FROM public.vw_book_mctr m
      ) mc ON true
    ON CONFLICT (portfolio_id, as_of, logic_version) DO NOTHING;

    SELECT count(*) INTO v_existing
      FROM public.position_verdicts pv
     WHERE pv.portfolio_id = v_pid AND pv.as_of = v_as_of AND pv.logic_version = p_logic_version;

    IF v_written = 0 AND v_existing = 0 THEN
        UPDATE public.sync_log
           SET status = 'error', finished_at = now(),
               error_message = 'wrote no verdict rows and none exist for this as_of',
               details = details || jsonb_build_object('preflight', v_pre)
         WHERE id = v_log_id;
        RAISE EXCEPTION 'verdict job produced no rows for % / % and none exist',
                        v_as_of, p_logic_version;
    END IF;

    UPDATE public.sync_log
       SET status = CASE WHEN v_written = 0 THEN 'skipped' ELSE 'success' END,
           finished_at = now(),
           error_message = CASE WHEN v_written = 0
                                THEN 'already written for this as_of' END,
           details = details || jsonb_build_object(
               'rows_written', v_written,
               'rows_present', v_existing,
               'cluster_risk_share_sum', v_share_sum,
               'preflight', v_pre,
               'notes', NULLIF(v_note, ''))
     WHERE id = v_log_id;

    RETURN QUERY SELECT v_as_of, p_logic_version, v_written,
                        NULLIF(v_note, '');
END;
$function$;
CREATE OR REPLACE FUNCTION public.atlas_write_segment_verdicts_active(p_as_of date DEFAULT NULL::date, p_logic_version text DEFAULT 'v1:rho0.75:n5:mwr'::text)
 RETURNS TABLE(out_as_of date, out_grouping text, out_rows_written integer, out_notes text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
    v_as_of    date;
    v_written  int;
    v_existing int;
    v_log_id   bigint;
    v_bad      text;
    v_sums     jsonb;
    v_pre      jsonb;
    v_replaced int := 0;
    v_pre_sums jsonb;
    v_failed   text;
    -- MP-5: the ACTIVE account; see atlas_write_verdicts_active.
    v_pid      uuid := public.atlas_active_portfolio();
BEGIN
    v_as_of := COALESCE(p_as_of, CURRENT_DATE);

    INSERT INTO public.sync_log (source, function_name, status, portfolio_id, started_at, details)
    VALUES ('atlas_write_segment_verdicts', 'atlas_write_segment_verdicts', 'running', v_pid, now(),
            jsonb_build_object('as_of', v_as_of, 'logic_version', p_logic_version))
    RETURNING id INTO v_log_id;

    -- Same gate as atlas_write_verdicts, shared rather than reimplemented:
    -- a segment row written against a stale or incoherent book is frozen
    -- into an append-only history that cannot be backfilled.
    SELECT jsonb_agg(jsonb_build_object('check', check_name, 'passed', passed,
                                        'detail', detail)),
           string_agg(check_name || ': ' || detail, '; ') FILTER (WHERE NOT passed)
      INTO v_pre, v_failed
      FROM public.atlas_verdict_preflight();

    IF v_failed IS NOT NULL THEN
        UPDATE public.sync_log
           SET status = 'skipped', finished_at = now(),
               details = details || jsonb_build_object('reason', 'preflight failed',
                                                      'preflight', v_pre)
         WHERE id = v_log_id;
        RETURN QUERY SELECT v_as_of, NULL::text, 0, 'preflight failed: ' || v_failed;
        RETURN;
    END IF;

    PERFORM public.atlas_rematerialise(ARRAY['mv_segment_ex_index']);

    -- Coverage is checked against the SNAPSHOT, before anything is
    -- written. Checking after the insert meant the only way to refuse
    -- was to RAISE, and the RAISE rolled back the sync_log row that
    -- recorded the refusal -- so the 2026-09-07 failure left nothing
    -- in the surface the platform monitors.
    SELECT jsonb_object_agg(g.grouping, jsonb_build_object('segmented', g.n, 'open', ob.n)),
           string_agg(g.grouping || ': ' || g.n || ' segmented vs ' || ob.n || ' open', '; ')
             FILTER (WHERE g.n <> ob.n)
      INTO v_pre_sums, v_bad
      FROM (SELECT grouping, count(*) n FROM public.vw_position_segments GROUP BY grouping) g
      CROSS JOIN (SELECT count(*) n FROM public.mv_position_returns
                   WHERE position_state = 'open') ob;

    IF v_bad IS NOT NULL THEN
        UPDATE public.sync_log
           SET status = 'error', finished_at = now(),
               error_message = 'segmentation does not cover the open book -- ' || v_bad,
               details = details || jsonb_build_object('coverage', v_pre_sums)
         WHERE id = v_log_id;
        RETURN;
    END IF;

    -- REPLACE, not append. Segment ids are derived from the clustering
    -- and are NOT stable across a re-run: 34 appeared and 35 retired
    -- between two writes of the same day. DO NOTHING then adds the new
    -- ids to the stale ones instead of skipping, and the day holds two
    -- segmentations at once.
    DELETE FROM public.segment_verdicts
     WHERE portfolio_id = v_pid AND as_of = v_as_of AND logic_version = p_logic_version;
    GET DIAGNOSTICS v_replaced = ROW_COUNT;

    WITH open_book AS (
        SELECT r.asset_id, r.symbol, r.engine_status, r.net_pnl_usd
          FROM public.mv_position_returns r
         WHERE r.position_state = 'open'
    ),
    -- §2.4b. Weight from vw_risk_analysis; the RISK MEASURE from the Euler
    -- MCTR (defect 3). The old `marginal_vol_contribution * weight` was
    -- weight^2 * vol -- positive by construction, so it could never report a
    -- segment that OFFSETS the book. `risk_contribution_annual` is already
    -- mctr x weight; multiplying again reintroduces exactly that bug.
    risk AS (
        SELECT v.symbol,
               v.weight AS w
          FROM public.vw_risk_analysis v
         WHERE v.symbol IN (SELECT symbol FROM open_book)
    ),
    -- One scan: vw_book_mctr is ~340-450 ms.
    mctr AS (
        SELECT m.symbol,
               m.risk_contribution_annual AS rc,
               m.matrix_as_of
          FROM public.vw_book_mctr m
         WHERE m.symbol IN (SELECT symbol FROM open_book)
    ),
    mx AS (SELECT max(matrix_as_of) AS d FROM mctr),
    -- One basis for every member's excess, on purpose. Members differ in
    -- which counterfactual their CARD is measured against (tier 1 vs tier 2),
    -- and a standard deviation taken across those two bases is not a
    -- dispersion of anything. Tier 2 covers the book, so tier 2 it is, and
    -- `dispersion_basis` says so on every row.
    memb AS (
        SELECT s.grouping, s.segment_id, s.segment_kind, s.segment_label,
               o.symbol, o.net_pnl_usd,
               mc.rc, r.w,
               t2.excess_vs_book_pct AS member_excess,
               bt.thesis_state
          FROM public.vw_position_segments s
          JOIN open_book o ON o.asset_id = s.asset_id
          LEFT JOIN risk r  ON r.symbol = o.symbol
          LEFT JOIN mctr mc ON mc.symbol = o.symbol
          LEFT JOIN public.mv_position_tier2 t2 ON t2.symbol = o.symbol
          LEFT JOIN public.vw_bench_thesis_state bt ON bt.symbol = o.symbol
    ),
    agg AS (
        SELECT m.grouping, m.segment_id,
               min(m.segment_kind)  AS segment_kind,
               min(m.segment_label) AS segment_label,
               count(*)             AS member_count,
               array_agg(m.symbol ORDER BY m.w DESC NULLS LAST) AS members,
               sum(m.rc)            AS rc,
               sum(m.w)             AS w,
               -- A member the matrix cannot price is COUNTED, never
               -- renormalised away.
               count(*) FILTER (WHERE m.rc IS NULL)  AS risk_withheld_n,
               sum(m.w) FILTER (WHERE m.rc IS NULL)  AS risk_withheld_w,
               sum(m.net_pnl_usd)   AS net_pnl_usd,
               stddev_samp(m.member_excess) AS dispersion,
               count(*) FILTER (WHERE m.thesis_state IS NOT NULL)::numeric
                 / NULLIF(count(*), 0)      AS thesis_coverage
          FROM memb m
         GROUP BY m.grouping, m.segment_id
    ),
    ext AS (
        SELECT a.*,
               a.rc / NULLIF(sum(a.rc) OVER (PARTITION BY a.grouping), 0) AS risk_share,
               a.w  / NULLIF(sum(a.w)  OVER (PARTITION BY a.grouping), 0) AS weight_share,
               a.net_pnl_usd
                 / NULLIF(sum(a.net_pnl_usd) OVER (PARTITION BY a.grouping), 0)
                 AS return_contribution_share,
               a.risk_withheld_n AS risk_members_withheld,
               CASE WHEN a.w IS NULL OR a.w = 0 THEN NULL
                    ELSE LEAST(100, GREATEST(0,
                         COALESCE(a.risk_withheld_w, 0) / a.w * 100)) END
                 AS risk_withheld_weight_pct
          FROM agg a
    ),
    best AS (
        SELECT DISTINCT ON (m.grouping, m.segment_id)
               m.grouping, m.segment_id, m.symbol AS sym, m.member_excess AS ex
          FROM memb m WHERE m.member_excess IS NOT NULL
         ORDER BY m.grouping, m.segment_id, m.member_excess DESC
    ),
    worst AS (
        SELECT DISTINCT ON (m.grouping, m.segment_id)
               m.grouping, m.segment_id, m.symbol AS sym, m.member_excess AS ex
          FROM memb m WHERE m.member_excess IS NOT NULL
         ORDER BY m.grouping, m.segment_id, m.member_excess ASC
    ),
    -- Count POSITIONS per label, not labels. jsonb_object_agg keeps the
    -- last value on a duplicate key, so grouping by (symbol, label) --
    -- where every count is 1 -- collapsed a segment to one entry per
    -- distinct label. Group by the key being counted, aggregate once.
    vc AS (
        SELECT g.grouping, g.segment_id, jsonb_object_agg(g.label, g.n) AS counts
          FROM (SELECT p.grouping, p.segment_id,
                       COALESCE(pv.verdict_label, 'unlabelled') AS label,
                       count(*) AS n
                  FROM public.vw_position_segments p
                  JOIN public.position_verdicts pv
                    ON pv.symbol = p.symbol
                   AND pv.portfolio_id = v_pid
                   AND pv.as_of = v_as_of
                   AND pv.logic_version = p_logic_version
                 GROUP BY p.grouping, p.segment_id,
                          COALESCE(pv.verdict_label, 'unlabelled')) g
         GROUP BY g.grouping, g.segment_id
    )
    INSERT INTO public.segment_verdicts (
        portfolio_id, as_of, logic_version, grouping, segment_id, segment_kind, segment_label,
        member_count, members, members_measured, members_withheld, withheld_symbols,
        weight_share, risk_share, return_contribution_share, net_pnl_usd,
        traded_mwr_pct, cf_mwr_pct, excess_vs_book_pct, cf_status, cf_reason,
        dispersion, best_member, best_member_excess_pct,
        worst_member, worst_member_excess_pct, dispersion_basis,
        thesis_coverage, verdict_counts,
        risk_basis, risk_matrix_as_of, risk_members_withheld, risk_withheld_weight_pct)
    SELECT v_pid, v_as_of, p_logic_version, e.grouping, e.segment_id, e.segment_kind, e.segment_label,
           e.member_count, e.members,
           cf.members_measured, cf.members_withheld, COALESCE(cf.withheld_symbols, '{}'),
           e.weight_share, e.risk_share, e.return_contribution_share, e.net_pnl_usd,
           cf.traded_mwr_pct, cf.cf_mwr_pct, cf.excess_vs_book_pct, cf.cf_status, cf.cf_reason,
           CASE WHEN e.member_count >= 2 THEN e.dispersion END,
           b.sym, b.ex, w.sym, w.ex,
           CASE WHEN e.member_count >= 2 AND e.dispersion IS NOT NULL
                THEN 'tier2:excess_vs_book' END,
           e.thesis_coverage,
           vc.counts,
           -- The basis is NULL exactly when the figure is.
           CASE WHEN e.risk_share IS NULL THEN NULL ELSE 'mctr_euler' END,
           CASE WHEN e.risk_share IS NULL THEN NULL ELSE mx.d END,
           e.risk_members_withheld,
           e.risk_withheld_weight_pct
      FROM ext e
      CROSS JOIN mx
      CROSS JOIN LATERAL public.atlas_counterfactual_segment(e.grouping, e.segment_id) cf
      LEFT JOIN best  b  ON b.grouping  = e.grouping AND b.segment_id  = e.segment_id
      LEFT JOIN worst w  ON w.grouping  = e.grouping AND w.segment_id  = e.segment_id
      LEFT JOIN vc       ON vc.grouping = e.grouping AND vc.segment_id = e.segment_id
    ON CONFLICT (portfolio_id, as_of, logic_version, grouping, segment_id) DO NOTHING;

    GET DIAGNOSTICS v_written = ROW_COUNT;

    -- ------------------------------------------------------------------
    -- The cross-row invariant: both shares close to 1.0, within EACH
    -- grouping. This is the §2.4b claim stated as a test.
    -- ------------------------------------------------------------------
    SELECT jsonb_object_agg(g.grouping,
                            jsonb_build_object('risk', round(g.r, 10),
                                               'weight', round(g.w, 10),
                                               'segments', g.n)),
           string_agg(g.grouping || ': risk ' || round(g.r, 6)::text
                                 || ', weight ' || round(g.w, 6)::text, '; ')
             FILTER (WHERE abs(g.r - 1.0) > 0.005 OR abs(g.w - 1.0) > 0.005)
      INTO v_sums, v_bad
      FROM (SELECT grouping, sum(risk_share) AS r, sum(weight_share) AS w, count(*) AS n
              FROM public.segment_verdicts
             WHERE portfolio_id = v_pid AND as_of = v_as_of AND logic_version = p_logic_version
             GROUP BY grouping) g;

    -- Belt and braces. The pre-write check above is the one that can
    -- report; by here the rows are committed-in-transaction, so a RAISE
    -- would take the log with it. Reaching this means the snapshot
    -- closed and the written rows did not, which is a real corruption
    -- and worth losing the log row to refuse.
    IF v_bad IS NOT NULL THEN
        RAISE EXCEPTION 'segment shares closed on the snapshot but not once written -- %', v_bad;
    END IF;

    SELECT count(*) INTO v_existing
      FROM public.segment_verdicts
     WHERE portfolio_id = v_pid AND as_of = v_as_of AND logic_version = p_logic_version;

    IF v_written = 0 AND v_existing = 0 THEN
        UPDATE public.sync_log
           SET status = 'error', finished_at = now(),
               error_message = 'wrote no segment rows and none exist for this as_of'
         WHERE id = v_log_id;
        RAISE EXCEPTION 'segment verdict job produced no rows for % / % and none exist',
                        v_as_of, p_logic_version;
    END IF;

    UPDATE public.sync_log
       SET status = CASE WHEN v_written = 0 THEN 'skipped' ELSE 'success' END,
           finished_at = now(),
           error_message = CASE WHEN v_written = 0
                                THEN 'already written for this as_of' END,
           details = details || jsonb_build_object(
               'rows_written', v_written,
               'rows_present', v_existing,
               'rows_replaced', v_replaced,
               'share_sums', v_sums,
               'preflight', v_pre)
     WHERE id = v_log_id;

    RETURN QUERY
    SELECT v_as_of, sv.grouping, count(*)::int, NULL::text
      FROM public.segment_verdicts sv
     WHERE sv.portfolio_id = v_pid AND sv.as_of = v_as_of AND sv.logic_version = p_logic_version
     GROUP BY sv.grouping;
END;
$function$;

-- ------------------------------------------------------------------------
-- 10. The scheduled entry points run every account
-- ------------------------------------------------------------------------
-- Same signatures and return shapes as before, so cron and any caller are
-- unchanged; one row per account (per grouping for segments), each note
-- prefixed with the account. An account whose run raises is logged against
-- that account and the next one still runs.
create or replace function public.atlas_write_verdicts(p_as_of date default null::date, p_logic_version text default 'v1:rho0.75:n5:mwr'::text, p_refresh boolean default true)
 returns table(out_as_of date, out_logic_version text, out_rows_written integer, out_notes text)
 language plpgsql
 security definer
 set search_path to 'public'
as $fn$
declare
  v_orig text := current_setting('request.headers', true);
  r      record;
  x      record;
begin
  for r in select p.id, p.name from public.portfolios p order by p.is_default desc, p.name loop
    begin
      perform set_config('request.headers',
                         json_build_object('x-atlas-portfolio', r.id::text)::text, true);
      for x in select * from public.atlas_write_verdicts_active(p_as_of, p_logic_version, p_refresh) loop
        out_as_of := x.out_as_of; out_logic_version := x.out_logic_version;
        out_rows_written := x.out_rows_written;
        out_notes := r.name || coalesce(': ' || x.out_notes, '');
        return next;
      end loop;
    exception when others then
      -- The account's own log row rolled back with its subtransaction.
      insert into public.sync_log (source, function_name, status, portfolio_id, started_at,
                                   finished_at, error_message, details)
      values ('atlas_write_verdicts', 'atlas_write_verdicts', 'error', r.id, clock_timestamp(),
              clock_timestamp(), sqlerrm,
              jsonb_build_object('portfolio', r.name, 'as_of', coalesce(p_as_of, current_date),
                                 'logic_version', p_logic_version));
      out_as_of := coalesce(p_as_of, current_date); out_logic_version := p_logic_version;
      out_rows_written := 0; out_notes := r.name || ': error: ' || sqlerrm;
      return next;
    end;
  end loop;
  perform set_config('request.headers', coalesce(v_orig, ''), true);
end
