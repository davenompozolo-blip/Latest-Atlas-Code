create view public.mv_segment_ex_index__compute as
 WITH day AS (
         SELECT b.price_date,
            sum(b.w) AS f,
            sum(b.wr) AS s
           FROM mv_book_daily_weights b
          GROUP BY b.price_date
        ), segs AS (
         SELECT DISTINCT p."grouping",
            p.segment_id
           FROM vw_position_segments p
        ), seg_day AS (
         SELECT p."grouping",
            p.segment_id,
            b.price_date,
            sum(b.w) AS w_s,
            sum(b.wr) AS wr_s
           FROM mv_book_daily_weights b
             JOIN vw_position_segments p ON p.asset_id = b.asset_id
          GROUP BY p."grouping", p.segment_id, b.price_date
        ), grid AS (
         SELECT s."grouping",
            s.segment_id,
            d.price_date,
            d.f,
            d.s AS s_tot,
            COALESCE(sd.w_s, 0::numeric) AS w_s,
            COALESCE(sd.wr_s, 0::numeric) AS wr_s,
            sd.segment_id IS NOT NULL AS segment_priced_that_day
           FROM segs s
             CROSS JOIN day d
             LEFT JOIN seg_day sd ON sd."grouping" = s."grouping" AND sd.segment_id = s.segment_id AND sd.price_date = d.price_date
        ), ex AS (
         SELECT g."grouping",
            g.segment_id,
            g.price_date,
            g.f,
            g.s_tot,
            g.w_s,
            g.wr_s,
            g.segment_priced_that_day,
                CASE
                    WHEN (g.f - g.w_s) < 0.02 THEN NULL::numeric
                    ELSE (g.s_tot - g.wr_s) / (g.f - g.w_s)
                END AS r_ex
           FROM grid g
        )
 SELECT "grouping",
    segment_id,
    price_date,
    r_ex,
    segment_priced_that_day,
    f - w_s AS surviving_weight,
    exp(sum(ln(1::numeric + r_ex)) OVER (PARTITION BY "grouping", segment_id ORDER BY price_date ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)) AS ex_index
   FROM ex
  WHERE r_ex IS NOT NULL AND r_ex > (- 1::numeric);
revoke all on public.mv_segment_ex_index__compute from public, anon, authenticated;

