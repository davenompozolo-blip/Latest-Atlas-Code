-- MP-5: the verdict engine runs per account.
--
-- MP-2 gated position verdicts, segment verdicts and everything under them to
-- the default account, because the six materialised views the engine rests on
-- are refreshed by pg_cron with no request header and so only ever held the
-- default book. Joined on asset_id to another account's rows they would have
-- attached Primary's verdicts to any name both accounts hold.
--
-- The fix is the MP-4d shape applied to a chain rather than one object:
--
--   <name>__acct     table, (portfolio_id, <the matview's columns>)
--   <name>           view over it for atlas_active_portfolio() -- the name every
--                    consumer (views, functions, the browser) already reads
--   <name>__compute  the matview's own definition, unchanged, as a view
--
-- A recompute sets the header to one account and runs each __compute in
-- dependency order; because every upstream name is itself per-account, each
-- stage reads the same account's upstream. Nothing downstream changes text
-- except the ten MP-2 guards on these sources, which are dropped: the sources
-- now answer for the active account instead of withholding it.
--
-- position_verdicts and segment_verdicts gain portfolio_id (existing rows are
-- the default account's, which is what the column default backfills), and the
-- writers run once per account under that account's header.
--
-- Sections 1-6 are generated from the live definitions (gen5b.py); 7-11 are
-- hand-written. book_factor_betas, book_regime_cvar and var_backtest_runs stay
-- default-only: they regress an account's own daily returns and Atlas Secondary
-- has one. They are recomputable later from portfolio_equity_curve, which is
-- already recorded per account, so nothing is lost by waiting.

