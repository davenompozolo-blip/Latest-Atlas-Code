-- 4. the computations the matviews used to hold, as views over the per-account names
create view public.mv_book_daily_weights__compute as
 WITH held AS (
         SELECT DISTINCT vw_position_nav_daily.asset_id
           FROM vw_position_nav_daily
        ), px AS (
         SELECT ph.asset_id,
            ph.price_date,
            ph.close,
            lag(ph.close) OVER (PARTITION BY ph.asset_id ORDER BY ph.price_date) AS prev_close
           FROM price_history ph
             JOIN held h ON h.asset_id = ph.asset_id
          WHERE ph."interval" = '1d'::text AND ph.price_date >= (( SELECT min(vw_position_nav_daily.price_date) - 10
                   FROM vw_position_nav_daily))
        ), ret AS (
         SELECT px.asset_id,
            px.price_date,
            px.close / px.prev_close - 1::numeric AS r
           FROM px
          WHERE px.prev_close > 0::numeric
        ), wt AS (
         SELECT n.asset_id,
            n.symbol,
            n.price_date,
            n.position_value / NULLIF(sum(n.position_value) OVER (PARTITION BY n.price_date), 0::numeric) AS w
           FROM vw_position_nav_daily n
          WHERE n.position_value IS NOT NULL
        )
 SELECT w.price_date,
    w.asset_id,
    w.symbol,
    w.w,
    r.r,
    w.w * r.r AS wr
   FROM wt w
     JOIN ret r ON r.asset_id = w.asset_id AND r.price_date = w.price_date;
revoke all on public.mv_book_daily_weights__compute from public, anon, authenticated;
create view public.mv_book_ex_index__compute as
 WITH day AS (
         SELECT mv_book_daily_weights.price_date,
            sum(mv_book_daily_weights.w) AS f,
            sum(mv_book_daily_weights.wr) AS s
           FROM mv_book_daily_weights
          GROUP BY mv_book_daily_weights.price_date
        ), universe AS (
         SELECT DISTINCT mv_book_daily_weights.asset_id,
            mv_book_daily_weights.symbol
           FROM mv_book_daily_weights
        ), grid AS (
         SELECT u.asset_id,
            u.symbol,
            d.price_date,
            d.f,
            d.s,
            COALESCE(m.w, 0::numeric) AS w_i,
            COALESCE(m.wr, 0::numeric) AS wr_i,
            m.asset_id IS NOT NULL AS present
           FROM universe u
             CROSS JOIN day d
             LEFT JOIN mv_book_daily_weights m ON m.asset_id = u.asset_id AND m.price_date = d.price_date
        ), ex AS (
         SELECT g.asset_id,
            g.symbol,
            g.price_date,
            g.f,
            g.s,
            g.w_i,
            g.wr_i,
            g.present,
                CASE
                    WHEN (g.f - g.w_i) < 0.02 THEN NULL::numeric
                    ELSE (g.s - g.wr_i) / (g.f - g.w_i)
                END AS r_ex
           FROM grid g
        )
 SELECT asset_id,
    symbol,
    price_date,
    r_ex,
    present AS asset_priced_that_day,
    f - w_i AS surviving_weight,
    exp(sum(ln(1::numeric + r_ex)) OVER (PARTITION BY asset_id ORDER BY price_date ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)) AS ex_index
   FROM ex
  WHERE r_ex IS NOT NULL AND r_ex > '-1'::integer::numeric;
revoke all on public.mv_book_ex_index__compute from public, anon, authenticated;
