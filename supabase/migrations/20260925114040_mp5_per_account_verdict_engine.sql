-- ------------------------------------------------------------------------
-- Replaces REFRESH MATERIALIZED VIEW. Recomputes the named entries, in the
-- order given, for whichever account the request header names (the default
-- when there is none). Callers that want every account loop and set the
-- header themselves, as atlas_refresh_verdict_inputs does below.
create or replace function public.atlas_rematerialise(p_names text[])
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $fn$
declare
  v_pid   uuid := public.atlas_active_portfolio();
  v_name  text;
  v_n     int;
  v_out   jsonb := '{}'::jsonb;
begin
  foreach v_name in array p_names loop
    if v_name <> all (array['mv_book_daily_weights','mv_book_ex_index','mv_position_returns',
                            'mv_position_tier1','mv_position_tier2','mv_segment_ex_index']) then
      raise exception 'atlas_rematerialise: % is not a per-account materialisation', v_name;
    end if;
    -- One transaction: a reader sees the previous rows until commit, the
    -- property REFRESH ... CONCURRENTLY was used for.
    execute format('delete from public.%I where portfolio_id = $1', v_name || '__acct') using v_pid;
    execute format('insert into public.%I select $1, c.* from public.%I c',
                   v_name || '__acct', v_name || '__compute') using v_pid;
    get diagnostics v_n = row_count;
    v_out := v_out || jsonb_build_object(v_name, v_n);
  end loop;
  return v_out;
end
$fn$;

-- Every account, each in its own subtransaction and with its own sync_log
-- row: one account failing neither blocks nor rolls back the other.
create or replace function public.atlas_rematerialise_all(p_names text[], p_label text)
returns void
language plpgsql
security definer
set search_path to 'public'
as $fn$
declare
  v_orig  text := current_setting('request.headers', true);
  r       record;
  v_log   bigint;
  v_rows  jsonb;
begin
  for r in select p.id, p.name from public.portfolios p order by p.is_default desc, p.name loop
    insert into public.sync_log (function_name, source, status, portfolio_id, started_at, details)
    values (p_label, 'pg_cron', 'running', r.id, clock_timestamp(),
            jsonb_build_object('portfolio', r.name, 'names', p_names))
    returning id into v_log;
    begin
      perform set_config('request.headers',
                         json_build_object('x-atlas-portfolio', r.id::text)::text, true);
      v_rows := public.atlas_rematerialise(p_names);
      update public.sync_log
         set status = 'success', finished_at = clock_timestamp(),
             details = details || jsonb_build_object('rows', v_rows)
       where id = v_log;
    exception when others then
      update public.sync_log
         set status = 'error', finished_at = clock_timestamp(), error_message = sqlerrm
       where id = v_log;
    end;
  end loop;
  perform set_config('request.headers', coalesce(v_orig, ''), true);
end
$fn$;

